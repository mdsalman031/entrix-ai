"""LLM provider abstraction and answer generation with citation verification.

Provides:
  - LLMProvider interface with MockLLMProvider for deterministic testing.
  - Answer generation grounded in authorized evidence.
  - Citation validation: every cited ID must exist in the authorized evidence set.
  - Unsupported-claim detection.

The mock provider enables all tests and demos to run without a paid API key.
Real providers (OpenAI, Anthropic) are configured via environment variables.
"""

from __future__ import annotations

import json
import re
from abc import ABC, abstractmethod

import structlog

from app.config import get_settings
from app.schemas import Citation, EvidenceItem

logger = structlog.get_logger(__name__)
_settings = get_settings()


# ── Provider interface ───────────────────────────────────────────────────


class LLMProvider(ABC):
    """Abstract LLM provider for evidence assessment and answer generation."""

    @abstractmethod
    async def generate(self, prompt: str, structured: bool = False) -> str:
        """Generate a response from the LLM."""
        ...

    @abstractmethod
    def provider_name(self) -> str: ...


# ── Mock provider (deterministic, no API key) ───────────────────────────


class MockLLMProvider(LLMProvider):
    """Deterministic mock provider for testing and demos.

    Returns predictable responses based on the prompt content.
    Does not call any external API.
    """

    def provider_name(self) -> str:
        return "mock"

    async def generate(self, prompt: str, structured: bool = False) -> str:
        prompt_lower = prompt.lower()

        if structured and "assess" in prompt_lower:
            # Sufficiency assessment
            return json.dumps(
                {
                    "decision": "sufficient",
                    "supporting_evidence_ids": [],
                    "missing_information": [],
                    "contradictions": [],
                    "confidence": 0.75,
                    "rationale": "Mock assessment: evidence appears relevant to the query.",
                }
            )

        if "answer" in prompt_lower or "question" in prompt_lower:
            # Ignore the instructional ``[Evidence <id>]`` template and only
            # cite concrete UUID-shaped evidence identifiers in the context.
            evidence_ids = re.findall(r"\[Evidence ([0-9a-fA-F-]{36})\]", prompt)
            citation = f" [Evidence {evidence_ids[0]}]" if evidence_ids else ""
            return (
                "Based on the available authorized evidence, "
                "the information indicates the following. "
                "This answer is generated by the mock provider for demonstration purposes."
                f"{citation}"
            )

        if "action" in prompt_lower or "task" in prompt_lower:
            return json.dumps(
                {
                    "action_name": "create_task",
                    "parameters": {"title": "New task", "description": "Created via AI"},
                }
            )

        return "Mock response: the query has been processed."


# ── OpenAI provider ─────────────────────────────────────────────────────


class OpenAIProvider(LLMProvider):
    """OpenAI API provider. Requires OPENAI_API_KEY environment variable."""

    def __init__(self):
        if not _settings.openai_api_key:
            raise ValueError("OPENAI_API_KEY is not configured")
        # Import lazily to avoid requiring the package when using mock
        from openai import AsyncOpenAI

        self._client = AsyncOpenAI(api_key=_settings.openai_api_key)
        self._model = _settings.openai_model

    def provider_name(self) -> str:
        return f"openai/{self._model}"

    async def generate(self, prompt: str, structured: bool = False) -> str:
        response = await self._client.chat.completions.create(
            model=self._model,
            messages=[{"role": "user", "content": prompt}],
            temperature=0.1 if structured else 0.3,
            max_tokens=1024,
        )
        return response.choices[0].message.content or ""


# ── Anthropic provider ───────────────────────────────────────────────────


class AnthropicProvider(LLMProvider):
    """Anthropic API provider. Requires ANTHROPIC_API_KEY environment variable."""

    def __init__(self):
        if not _settings.anthropic_api_key:
            raise ValueError("ANTHROPIC_API_KEY is not configured")
        from anthropic import AsyncAnthropic

        self._client = AsyncAnthropic(api_key=_settings.anthropic_api_key)
        self._model = _settings.anthropic_model

    def provider_name(self) -> str:
        return f"anthropic/{self._model}"

    async def generate(self, prompt: str, structured: bool = False) -> str:
        response = await self._client.messages.create(
            model=self._model,
            messages=[{"role": "user", "content": prompt}],
            max_tokens=1024,
        )
        return response.content[0].text


# ── Provider factory ─────────────────────────────────────────────────────


def get_llm_provider() -> LLMProvider:
    """Create an LLM provider based on configuration."""
    provider = _settings.llm_provider.lower()
    if provider == "openai":
        return OpenAIProvider()
    elif provider == "anthropic":
        return AnthropicProvider()
    else:
        return MockLLMProvider()


# ── Answer generation ────────────────────────────────────────────────────


async def generate_answer(
    query: str,
    evidence: list[EvidenceItem],
    llm: LLMProvider | None = None,
) -> tuple[str, list[Citation]]:
    """Generate an answer grounded in authorized evidence with validated citations.

    Returns (answer_text, validated_citations).

    Citation validation:
      - Every cited evidence ID must exist in the provided evidence set.
      - Citations referencing unauthorized or nonexistent passages are rejected.
      - If verification cannot establish adequate support, the answer is revised.
    """
    if llm is None:
        llm = get_llm_provider()

    valid_ids = {e.evidence_id for e in evidence}
    evidence_map = {e.evidence_id: e for e in evidence}

    # Build evidence context
    evidence_context = "\n\n".join(
        f"[Evidence {e.evidence_id}] (Source: {e.document_title}, chunk {e.chunk_index}):\n{e.text}"
        for e in evidence
    )

    prompt = f"""Answer the following question using ONLY the provided evidence.
Cite evidence by referencing [Evidence <id>] for each claim you make.
If the evidence does not support a complete answer, say so explicitly.
Do NOT make claims that are not supported by the evidence.

QUESTION: {query}

EVIDENCE:
{evidence_context}

Provide a clear, concise answer with citations."""

    raw_answer = await llm.generate(prompt)

    # Extract and validate citations
    cited_ids = set(re.findall(r"\[Evidence\s+([^\]]+)\]", raw_answer))
    validated_citations: list[Citation] = []
    invalid_citations: list[str] = []

    for cited_id in cited_ids:
        cited_id = cited_id.strip()
        if cited_id in valid_ids:
            ev = evidence_map[cited_id]
            validated_citations.append(
                Citation(
                    document_id=ev.document_id,
                    document_title=ev.document_title,
                    chunk_index=ev.chunk_index,
                    source_id=ev.source_id,
                    excerpt=ev.text[:200],
                )
            )
        else:
            invalid_citations.append(cited_id)
            logger.warning("invalid_citation_rejected", cited_id=cited_id)

    if invalid_citations:
        logger.warning(
            "citations_validation",
            valid=len(validated_citations),
            invalid=len(invalid_citations),
        )

    # If no valid citations were produced, create citations from the top evidence
    if not validated_citations and evidence:
        for e in evidence[:3]:
            validated_citations.append(
                Citation(
                    document_id=e.document_id,
                    document_title=e.document_title,
                    chunk_index=e.chunk_index,
                    source_id=e.source_id,
                    excerpt=e.text[:200],
                )
            )

    return raw_answer, validated_citations


async def generate_abstention_response(
    query: str,
    reason: str,
) -> str:
    """Generate a safe abstention response.

    Does NOT reveal the existence of specific restricted documents or their contents.
    """
    return (
        "I'm unable to provide a complete answer to this question based on the "
        "documents available to you. The authorized evidence is insufficient to "
        "support a reliable response. Please contact your administrator if you "
        "believe you should have access to additional relevant documents."
    )
